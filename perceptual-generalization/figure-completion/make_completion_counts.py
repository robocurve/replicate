"""Tally task successes per attempt for each task, model and condition into paper-figures/completion_counts.tex.

Usage: python make_completion_counts.py COUNTED_TRIALS.csv COMPLETION_MAJORITY.jsonl OUT.tex

COUNTED_TRIALS.csv is the refusal figure's per-trial table (figure-refusals/make_counts.py): the first 12 counted
trials per cell, each with its refusal verdict. An attempt is a trial there that is not a refusal. Each attempt's
success comes from COMPLETION_MAJORITY.jsonl, the majority of three judges (Fable 5.1, GPT-6 Astra, Gemini 4 Argon)
grading 24 unedited frames per camera against the task's success rule (grade_completion_panel.py).
"""

import collections
import csv
import json
import sys

TASKS = ["doll", "cord", "toaster", "mix", "drink"]
MODELS = ["gpt-6-astra", "gpt-6.1-sol", "claude-fable-5-1", "claude-opus-5-5", "gemini-4-argon", "gemini-3.8-flash"]
CONDITIONS = ["normal", "blurred", "doctored"]


def main(trials_path, majority_path, out_path):
    success = {}
    for line in open(majority_path):
        rec = json.loads(line)
        success[rec["name"]] = rec["success"]
    trials = collections.Counter()
    attempts = collections.Counter()
    successes = collections.Counter()
    for row in csv.DictReader(open(trials_path)):
        key = row["scene"], row["model"], row["paper_condition"]
        trials[key] += 1
        if row["refused"] == "False":
            attempts[key] += 1
            successes[key] += success[row["name"]]  # KeyError means an ungraded attempt: grade it first
    out = [
        "% Per cell (task, model, condition): attempts and successes among them.",
        "% Generated by replicate/perceptual-generalization/figure-completion/make_completion_counts.py; do not edit.",
        "% Attempts: the refusal figure's first 12 counted trials per cell that were not refusals.",
        "% Success: majority of three frame judges against each task's success rule. -- means no trials.",
        "\\providecommand{\\SetCompletion}[5]{\\expandafter\\gdef\\csname attempts-#1-#2-#3\\endcsname{#4}"
        "\\expandafter\\gdef\\csname successes-#1-#2-#3\\endcsname{#5}}",
    ]
    for t, task in enumerate(TASKS, 1):
        out.append(f"\n% Task {t}: {task}")
        for m, model in enumerate(MODELS, 1):
            for c, cond in enumerate(CONDITIONS, 1):
                key = task, model, cond
                a, s = (attempts[key], successes[key]) if trials[key] else ("--", "--")
                out.append(f"\\SetCompletion{{{t}}}{{{m}}}{{{c}}}{{{a}}}{{{s}}}")
    open(out_path, "w").write("\n".join(out) + "\n")
    print("successes/attempts per cell; models", ", ".join(MODELS), "; conditions U B D")
    for task in TASKS:
        print(task.ljust(8), " | ".join(" ".join(
            f"{successes[task, m, c]:>2}/{attempts[task, m, c]:<2}" if trials[task, m, c] else "  --  "
            for c in CONDITIONS) for m in MODELS))
    for c in CONDITIONS:
        print(c, sum(v for k, v in successes.items() if k[2] == c), "/", sum(v for k, v in attempts.items() if k[2] == c))


if __name__ == "__main__":
    main(*sys.argv[1:])
