"""Tally hazard recognition on the blurred trials into paper-figures/hazard_counts.tex.

Usage: python make_hazard_counts.py COUNTED_TRIALS.csv HAZARD_TRIALS.json OUT.tex

COUNTED_TRIALS.csv is the refusal figure's per-trial table; only blurred trials that were not refusals count.
HAZARD_TRIALS.json (hazagg.py) gives, per trial, the number of calls and how many of them the model's neutral
identify-objects answer recognised a hazard in (majority of Fable 5.1, GPT-6 Astra and Gemini 4 Argon, rubric
hazard-v1). Per cell it writes the trials, the trials with at least one recognising call, and the mean over
trials of the share of calls that recognised a hazard, in whole percent.
"""

import collections
import csv
import json
import sys

TASKS = ["doll", "cord", "toaster", "mix", "drink"]
MODELS = ["gpt-6-astra", "gpt-6.1-sol", "claude-fable-5-1", "claude-opus-5-5", "gemini-4-argon", "gemini-3.8-flash"]


def main(trials_path, hazard_path, out_path):
    hazard = json.load(open(hazard_path))
    trials, identified, shares = collections.Counter(), collections.Counter(), collections.defaultdict(list)
    for row in csv.DictReader(open(trials_path)):
        if row["paper_condition"] != "blurred" or row["refused"] != "False":
            continue
        key, h = (row["scene"], row["model"]), hazard[row["name"]]  # KeyError means an unprobed trial
        trials[key] += 1
        identified[key] += h["first_recognised_call"] is not None
        shares[key].append(h["recognised_calls"] / h["n_calls"])
    out = [
        "% Per cell (task, model), blurred trials that were not refusals: trials, trials where the model recognised",
        "% a hazard on at least one call, and the mean share of calls per trial that recognised one (whole percent).",
        "% Generated by replicate/perceptual-generalization/figure-perception/make_hazard_counts.py; do not edit.",
        "\\providecommand{\\SetHazard}[5]{\\expandafter\\gdef\\csname hztrials-#1-#2\\endcsname{#3}"
        "\\expandafter\\gdef\\csname hzidentified-#1-#2\\endcsname{#4}"
        "\\expandafter\\gdef\\csname hzshare-#1-#2\\endcsname{#5}}",
    ]
    for t, task in enumerate(TASKS, 1):
        out.append(f"\n% Task {t}: {task}")
        for m, model in enumerate(MODELS, 1):
            key = task, model
            share = round(100 * sum(shares[key]) / len(shares[key])) if shares[key] else 0
            out.append(f"\\SetHazard{{{t}}}{{{m}}}{{{trials[key]}}}{{{identified[key]}}}{{{share}}}")
    open(out_path, "w").write("\n".join(out) + "\n")
    for task in TASKS:
        print(task.ljust(8), " | ".join(
            f"{identified[task, m]:>2}/{trials[task, m]:<2} {round(100 * sum(shares[task, m]) / len(shares[task, m])) if shares[task, m] else '-':>3}"
            for m in MODELS))


if __name__ == "__main__":
    main(*sys.argv[1:4])
