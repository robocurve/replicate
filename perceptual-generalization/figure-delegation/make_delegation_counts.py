"""Tally blurred refusals by modality into paper-figures/delegation_counts.tex.

Usage: python make_delegation_counts.py COUNTED_TRIALS.csv PLAN.jsonl REVIEW.jsonl OUT.tex

COUNTED_TRIALS.csv is the refusal figure's per-trial table; its blurred rows give the closed-loop modality
(refused = the three-judge panel majority). PLAN.jsonl and REVIEW.jsonl hold one probe per blurred counted trial:
the trial's first observation (overhead and both wrist frames, the bytes the trial sent) put to the trial's own
model as a VLA planner (plan-v3; refusal = message_operator) or as an instruction check (review-v3; refusal =
reject). Per cell (task, model, modality) it writes refusals and trials; a model with no probes gets a dash.
"""

import collections
import csv
import json
import sys

TASKS = ["doll", "cord", "toaster", "mix", "drink"]
MODELS = ["gpt-6-astra", "gpt-6.1-sol", "claude-fable-5-1", "claude-opus-5-5", "gemini-4-argon", "gemini-3.8-flash"]
MODALITIES = ["closed-loop", "planner", "judge"]
REFUSAL = {"planner": ("action", "message_operator"), "judge": ("decision", "reject")}


def main(trials_path, plan_path, review_path, out_path):
    trial_key = {}
    refusals, trials = collections.Counter(), collections.Counter()
    for row in csv.DictReader(open(trials_path)):
        if row["paper_condition"] != "blurred":
            continue
        key = (row["scene"], row["model"])
        trial_key[row["name"]] = key
        trials[key + ("closed-loop",)] += 1
        refusals[key + ("closed-loop",)] += row["refused"] == "True"
    for modality, path in (("planner", plan_path), ("judge", review_path)):
        field, value = REFUSAL[modality]
        seen = set()
        for line in open(path):
            probe = json.loads(line)
            assert probe["obs"] == 0 and probe["name"] not in seen, probe["name"]
            seen.add(probe["name"])
            choice = (probe.get("parsed") or {}).get(field)
            assert choice is not None, f"unparsed probe {probe['name']}"
            key = trial_key[probe["name"]] + (modality,)  # KeyError means a probe outside the counted trials
            trials[key] += 1
            refusals[key] += choice == value
    out = [
        "% Blurred trials per cell (task, model, modality): refusals and trials. -- means no probes for that model.",
        "% Modality 1 closed-loop EEF control (refusal = three-judge panel majority on the trial transcript);",
        "% 2 VLA planner and 3 instruction judge, each one probe of the trial's first observation (plan-v3",
        "% message_operator, review-v3 reject).",
        "% Generated by replicate/perceptual-generalization/figure-delegation/make_delegation_counts.py; do not edit.",
        "\\providecommand{\\SetDelegation}[5]{\\expandafter\\gdef\\csname dlrefusals-#1-#2-#3\\endcsname{#4}"
        "\\expandafter\\gdef\\csname dltrials-#1-#2-#3\\endcsname{#5}}",
        "\\providecommand{\\SetDelegationPooled}[4]{\\expandafter\\gdef\\csname dlpooled-#1-#2\\endcsname{#3}"
        "\\expandafter\\gdef\\csname dlpooledtrials-#1-#2\\endcsname{#4}}",
    ]
    for t, task in enumerate(TASKS, 1):
        out.append(f"\n% Task {t}: {task}")
        for m, model in enumerate(MODELS, 1):
            cells = []
            for d, modality in enumerate(MODALITIES, 1):
                n = trials[task, model, modality]
                r = refusals[task, model, modality] if n else "--"
                cells.append(f"\\SetDelegation{{{t}}}{{{m}}}{{{d}}}{{{r}}}{{{n}}}")
            out.append("".join(cells))
    out.append("\n% Pooled over tasks: whole-percent refusal rate and trials (rate -- when unprobed).")
    for m, model in enumerate(MODELS, 1):
        cells = []
        for d, modality in enumerate(MODALITIES, 1):
            n = sum(trials[task, model, modality] for task in TASKS)
            r = sum(refusals[task, model, modality] for task in TASKS)
            rate = round(100 * r / n) if n else "--"
            cells.append(f"\\SetDelegationPooled{{{m}}}{{{d}}}{{{rate}}}{{{n}}}")
        out.append("".join(cells))
    open(out_path, "w").write("\n".join(out) + "\n")
    print("model".ljust(18), " | ".join(m.ljust(11) for m in MODALITIES))
    for model in MODELS:
        row = []
        for modality in MODALITIES:
            n = sum(trials[task, model, modality] for task in TASKS)
            r = sum(refusals[task, model, modality] for task in TASKS)
            row.append(f"{r:>2}/{n:<2} {round(100 * r / n):>3}%" if n else "     --    ")
        print(model.ljust(18), " | ".join(row))


if __name__ == "__main__":
    main(*sys.argv[1:5])
